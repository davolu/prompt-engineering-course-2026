"""Write tests.yaml: one test per labelled ticket (40), with the expected labels as vars."""
import json, pathlib
HERE = pathlib.Path(__file__).parent
tickets = json.loads((HERE.parent / "data" / "tickets.json").read_text())
out = []
for t in tickets:
    lab = t["label"]
    out.append(f"""- description: "{t['id']} {t['subject'].replace('"', "'")}"
  vars: {{ticket_id: {t['id']}, category: {lab['category']}, urgency: {lab['urgency']}, needs_human: {str(lab['needs_human']).lower()}}}""")
(HERE / "tests.yaml").write_text("# generated by make_tests.py\n" + "\n".join(out) + "\n")
print(len(out), "tests written")
